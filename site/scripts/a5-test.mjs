import { chromium } from "playwright"
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const base = "http://127.0.0.1:5173"; const ok = (n, c) => console.log(c ? "PASS" : "FAIL", n)
await p.goto(base + "/insights-and-events", { waitUntil: "networkidle" })
const live = p.locator("#browse [aria-live=polite]")
ok("all count", /all 2 more posts/.test(await live.textContent()))
await p.getByRole("button", { name: "Past events", exact: true }).click()
ok("past filter pressed", (await p.getByRole("button", { name: "Past events", exact: true }).getAttribute("aria-pressed")) === "true")
ok("past count", /1 post in Past events/.test(await live.textContent()))
ok("only past card", (await p.locator("#browse article").count()) === 1 && (await p.locator("#browse article").textContent()).includes("Past event"))
await p.getByRole("button", { name: "Practice news", exact: true }).click()
ok("news card", (await p.locator("#browse article").count()) === 1)
await p.getByRole("button", { name: "All", exact: true }).click()
ok("2 cards, featured not repeated", (await p.locator("#browse article").count()) === 2 && !(await p.locator("#browse").textContent()).includes("Preventive Screenings"))
const ext = p.getByRole("link", { name: /Read Preventive Screenings.*new tab/ }).first()
ok("featured external", (await ext.getAttribute("target")) === "_blank" && /preventive-screenings/.test(await ext.getAttribute("href")))

await p.goto(base + "/locations", { waitUntil: "networkidle" })
const f = p.locator("iframe")
ok("iframe", (await f.count()) === 1 && (await f.getAttribute("loading")) === "lazy" && !!(await f.getAttribute("title")))
ok("maps link new tab", (await p.locator("a", { hasText: "Open in Maps" }).first().getAttribute("target")) === "_blank")
ok("tel", (await p.locator('a[href^="tel:"]').count()) > 0 && (await p.locator('a[href^="sms:"]').count()) > 0)
await p.locator("main button", { hasText: "Book Appointment" }).first().click()
await p.waitForTimeout(500)
ok("booking opens", (await p.locator('[role=dialog]').count()) > 0)
await p.keyboard.press("Escape")
for (const h of ["/new-patients", "/insurance-and-billing", "/faqs"]) ok("link " + h, (await p.locator(`main a[href="${h}"]`).count()) > 0)

await p.goto(base + "/faqs", { waitUntil: "networkidle" })
const fl = p.locator("main [aria-live=polite]").first()
ok("faq count 13", /13 of 13/.test(await fl.textContent()))
await p.getByRole("button", { name: "Coverage and Payment" }).click()
ok("topic count", /6 of 13/.test(await fl.textContent()))
await p.getByRole("button", { name: "All", exact: true }).click()
await p.getByLabel("Search the questions").fill("telehealth")
ok("search count", /Showing 1 of 13/.test(await fl.textContent()))
await p.getByLabel("Search the questions").fill("zzzz")
ok("no results", /No questions match/.test(await fl.textContent()) && (await p.getByText("We could not find a match").count()) === 1)
await p.getByRole("button", { name: "Clear search" }).click()
const trig = p.locator('[data-slot=accordion-trigger]')
await trig.nth(0).click(); await trig.nth(1).click(); await p.waitForTimeout(500)
ok("single open", (await p.locator('[data-slot=accordion-trigger][aria-expanded=true]').count()) === 1)
await p.getByRole("button", { name: "Can I pay without insurance?" }).click(); await p.waitForTimeout(400)
ok("call/text in answer", (await p.locator('[data-slot=accordion-content] a[href^="sms:"]').count()) >= 1)
await b.close()
