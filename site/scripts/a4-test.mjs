import { chromium } from "playwright"
import path from "node:path"
import fs from "node:fs"
const base = "http://127.0.0.1:5173"
const out = path.resolve(import.meta.dirname, "../../cook/stills/ra4/tests")
fs.mkdirSync(out, { recursive: true })
const browser = await chromium.launch()
const log = (...a) => console.log(...a)
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const page = await ctx.newPage()
const errs = []
page.on("pageerror", (e) => errs.push(String(e)))
page.on("console", (m) => m.type() === "error" && errs.push(m.text()))
const noReveal = () => page.addStyleTag({ content: ".reveal{opacity:1!important;transform:none!important;transition:none!important}" })

// Insurance
await page.goto(base + "/insurance-and-billing", { waitUntil: "networkidle" })
await noReveal()
const status = () => page.locator("#insurers [role=status]").first().innerText()
log("count initial:", await status())
await page.fill("#insurer-search", "cig")
log("count cig:", await status(), "cards:", await page.locator("#insurers button[aria-pressed]").count())
await page.fill("#insurer-search", "zzz")
log("count zzz:", await status(), "empty state:", await page.getByText("We could not find").count())
await page.fill("#insurer-search", "")
await page.locator("#insurers button[aria-pressed]", { hasText: "Ambetter" }).click()
log("pressed ambetter:", await page.locator("#insurers button[aria-pressed=true]").innerText())
log("guide:", (await page.locator("aside[aria-label='Company guide']").innerText()).replace(/\n+/g, " | "))
// keyboard
await page.locator("#insurers button[aria-pressed]", { hasText: "Medicare" }).focus()
await page.keyboard.press("Enter")
log("kbd medicare pressed:", await page.locator("#insurers button[aria-pressed=true]").innerText())
const href = await page.locator("aside[aria-label='Company guide'] a", { hasText: "website" }).getAttribute("href")
const tgt = await page.locator("aside[aria-label='Company guide'] a", { hasText: "website" }).getAttribute("target")
log("guide link:", href, tgt)
await page.locator("#insurers").screenshot({ path: path.join(out, "insurers-mobile.png") })
await page.fill("#insurer-search", "xyz")
await page.locator("#insurers").screenshot({ path: path.join(out, "insurers-empty-mobile.png") })

// Checklist
await page.goto(base + "/new-patients", { waitUntil: "networkidle" })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: "networkidle" })
await noReveal()
const pb = page.locator("[role=progressbar]")
log("progress start:", await pb.getAttribute("aria-valuenow"))
await page.getByText("Photo ID", { exact: true }).click()
await page.getByText("Medicines and allergies", { exact: true }).click()
log("progress after 2:", await pb.getAttribute("aria-valuenow"), await pb.getAttribute("aria-valuetext"))
log("checked boxes:", await page.locator("[role=checkbox][aria-checked=true]").count())
await page.locator("#checklist").screenshot({ path: path.join(out, "checklist-mobile.png") })
await page.getByRole("button", { name: "Clear the checklist" }).click()
log("progress after clear:", await pb.getAttribute("aria-valuenow"))

// Contact form
await page.goto(base + "/contact", { waitUntil: "networkidle" })
await noReveal()
await page.getByRole("button", { name: "Send question" }).click()
log("errors:", (await page.locator("form [id$=-error]").allInnerTexts()).join(" | "))
log("aria-invalid count:", await page.locator("form [aria-invalid=true]").count(), "focused:", await page.evaluate(() => document.activeElement?.id))
await page.locator("form").screenshot({ path: path.join(out, "contact-errors-mobile.png") })
await page.fill("#contact-name", "Test Person")
await page.fill("#contact-email", "bad")
await page.getByRole("button", { name: "Send question" }).click()
log("email err:", await page.locator("#contact-email-error").innerText())
await page.fill("#contact-email", "a@b.co")
await page.locator("#contact-topic").click()
await page.getByRole("option", { name: "Insurance" }).click()
log("topic value:", await page.locator("#contact-topic").innerText())
await page.fill("#contact-message", "Do you take my plan?")
await page.getByRole("button", { name: "Send question" }).click()
log("success:", (await page.locator("[role=status]").last().innerText()).replace(/\n+/g, " | "))
await page.locator("[role=status]").last().screenshot({ path: path.join(out, "contact-success-mobile.png") })
log("tel link:", await page.locator("[role=status] a[href^='tel:']").count())
log("iframe:", await page.locator("iframe").getAttribute("loading"), await page.locator("iframe").getAttribute("title"))

// Portal
await page.goto(base + "/patient-portal", { waitUntil: "networkidle" })
const a = page.getByRole("link", { name: /Continue to Patient Portal/ })
log("portal:", await a.getAttribute("href"), await a.getAttribute("target"), await a.getAttribute("rel"))
log("errors:", errs.filter((e) => !/maps|google|ERR_/i.test(e)))
await browser.close()
