import { chromium } from "playwright"
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs=[]; p.on("pageerror",e=>errs.push(String(e)))
await p.goto("http://127.0.0.1:5173/about", { waitUntil: "networkidle" })
const src = () => p.locator('#story [data-slot="tabs-content"] img').first().getAttribute("src")
const s1 = await src()
await p.getByRole("tab", { name: "Building the practice in Frisco" }).click()
await p.waitForTimeout(300)
const s3 = await src()
console.log("tab image changed:", s1, "->", s3, s1 !== s3)
await p.getByRole("button", { name: "Read the Fuller Story" }).click()
await p.waitForTimeout(300)
console.log("story dialog open:", await p.getByRole("dialog").count())
await p.keyboard.press("Escape"); await p.waitForTimeout(400)
console.log("story dialog closed:", await p.getByRole("dialog").count())
const btns = p.locator("#team").getByRole("button", { name: "Learn More" })
console.log("learn more buttons:", await btns.count())
await btns.nth(2).click(); await p.waitForTimeout(300)
console.log("person dialog:", (await p.getByRole("dialog").innerText()).slice(0,200).replace(/\n/g," | "))
await p.keyboard.press("Escape"); await p.waitForTimeout(400)
console.log("person closed:", await p.getByRole("dialog").count())
await p.goto("http://127.0.0.1:5173/providers#anupa-adhikari", { waitUntil: "networkidle" })
await p.waitForTimeout(1500)
console.log("hash scroll top of #anupa-adhikari:", await p.evaluate(()=>Math.round(document.getElementById("anupa-adhikari").getBoundingClientRect().top)))
await p.goto("http://127.0.0.1:5173/providers", { waitUntil: "networkidle" })
await p.getByRole("link", { name: "Dr. Kantamneni" }).first().click()
await p.waitForTimeout(1500)
console.log("jump link top:", await p.evaluate(()=>Math.round(document.getElementById("sylaza-kantamneni").getBoundingClientRect().top)), p.url())
const col = p.getByRole("button", { name: "Education and background" }).first()
await col.click(); await p.waitForTimeout(500)
console.log("collapsible expanded:", await col.getAttribute("aria-expanded"))
await p.getByRole("button", { name: "Ask About an Appointment" }).first().click()
await p.waitForTimeout(300)
console.log("booking panel:", (await p.getByRole("dialog").innerText()).slice(0,40).replace(/\n/g," "))
await p.keyboard.press("Escape")
// mobile tabs
const m = await b.newPage({ viewport: { width: 390, height: 844 } })
await m.goto("http://127.0.0.1:5173/about", { waitUntil: "networkidle" })
await m.getByRole("tab", { name: "Continuing to learn with patients" }).click({force:true})
await m.waitForTimeout(300)
console.log("mobile tab:", (await m.locator('#story [data-slot="tabs-content"] h3').innerText()))
console.log("errors:", errs)
await b.close()
